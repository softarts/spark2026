#!/usr/bin/env bash
# Start (or re-apply) the whole Spark Platform Learning Lab, idempotently:
#   Docker Desktop Kubernetes -> runtime image -> Silo -> portal + Ingress
#   -> Traefik -> JupyterHub
# Then open http://localhost:8080 (or http://<mac-ip>:8080 from another machine).
#
# Usage: ./startcluster.sh [--no-build]
#   --no-build   skip `docker build` of the runtime image (it must already exist)
set -euo pipefail
source "$(dirname "$0")/scripts/common.sh"

BUILD=1
for arg in "$@"; do
  case "$arg" in
    --no-build) BUILD=0 ;;
    -h|--help) sed -n '2,9p' "$0"; exit 0 ;;
    *) die "unknown option: $arg" ;;
  esac
done

require_tools docker kubectl helm openssl python3
cd "$LAB_ROOT"
trap stop_loader EXIT

log "1/8 Checking Docker Desktop Kubernetes (context: $LAB_CONTEXT)"
ensure_cluster

log "2/8 Runtime image $RUNTIME_IMAGE"
want_hash=$(inputs_hash)
have_hash=$(docker image inspect "$RUNTIME_IMAGE" \
  --format "{{index .Config.Labels \"$HASH_LABEL\"}}" 2>/dev/null || true)
if [ "$BUILD" -eq 0 ]; then
  [ -n "$have_hash" ] || die "$RUNTIME_IMAGE does not exist; run without --no-build"
  want_hash="$have_hash"
elif [ "$have_hash" != "$want_hash" ]; then
  log "    building (images/, jobs/ or notebooks/ changed)"
  docker build --quiet --platform linux/arm64 \
    --build-arg LAB_INPUTS_HASH="$want_hash" \
    -t "$RUNTIME_IMAGE" -f images/Dockerfile . >/dev/null
else
  log "    up to date (inputs $want_hash)"
fi
sync_image_to_node "$RUNTIME_IMAGE" "$want_hash"

log "3/8 Preparing local credentials ($CRED_FILE)"
mkdir -p "$(dirname "$CRED_FILE")"
if [ ! -f "$CRED_FILE" ]; then
  # Reuse an existing Silo secret so existing objects stay accessible.
  ak=$(kc -n "$LAB_NAMESPACE" get secret silo-root-credentials -o jsonpath='{.data.accessKey}' 2>/dev/null | base64 -d || true)
  sk=$(kc -n "$LAB_NAMESPACE" get secret silo-root-credentials -o jsonpath='{.data.secretKey}' 2>/dev/null | base64 -d || true)
  umask 077
  cat > "$CRED_FILE" <<EOF
# Generated by startcluster.sh. Local only; git-ignored. Edit and re-run
# startcluster.sh to change a value.
# JUPYTER_USER/PASSWORD: the platform admin account (pre-registered in
# NativeAuthenticator). Other users self-register at /hub/signup.
JUPYTER_USER=spark
JUPYTER_PASSWORD=$(openssl rand -hex 8)
# Silo root: for the Silo Console admin login and for startcluster/silo-export.
SILO_ACCESS_KEY=${ak:-silo-admin}
SILO_SECRET_KEY=${sk:-$(openssl rand -hex 16)}
# Silo shared NON-root user, handed to every Notebook (bucket spark-data only).
SILO_SHARED_ACCESS_KEY=lab-user
SILO_SHARED_SECRET_KEY=$(openssl rand -hex 16)
EOF
fi
# shellcheck disable=SC1090
source "$CRED_FILE"

# Add keys introduced after a credentials file was first written (older files
# from the single-user version lack the shared Silo user).
if [ -z "${SILO_SHARED_ACCESS_KEY:-}" ]; then
  {
    echo "# Silo shared NON-root user, handed to every Notebook (bucket spark-data only)."
    echo "SILO_SHARED_ACCESS_KEY=lab-user"
    echo "SILO_SHARED_SECRET_KEY=$(openssl rand -hex 16)"
  } >> "$CRED_FILE"
  # shellcheck disable=SC1090
  source "$CRED_FILE"
fi

log "4/8 Applying namespace, RBAC, Driver Services and Silo"
kc apply -f k8s/00-namespace.yaml >/dev/null
kc -n "$LAB_NAMESPACE" create secret generic silo-root-credentials \
  --from-literal=accessKey="$SILO_ACCESS_KEY" \
  --from-literal=secretKey="$SILO_SECRET_KEY" \
  --dry-run=client -o yaml | kc apply -f - >/dev/null
kc apply -f k8s/10-spark-rbac.yaml \
         -f k8s/11-hub-rbac.yaml \
         -f k8s/21-cluster-driver-ui-service.yaml \
         -f k8s/30-silo.yaml >/dev/null
# Remove single-user-era objects (replaced by the per-user namespace model).
kc -n "$LAB_NAMESPACE" delete pod jupyter-spark --ignore-not-found --now >/dev/null 2>&1 || true
kc -n "$LAB_NAMESPACE" delete pvc claim-spark --ignore-not-found >/dev/null 2>&1 || true
kc delete -f k8s/20-client-driver-service.yaml --ignore-not-found >/dev/null 2>&1 || true
kc -n "$LAB_NAMESPACE" delete serviceaccount spark-client --ignore-not-found >/dev/null 2>&1 || true
kc -n "$LAB_NAMESPACE" delete role spark-driver --ignore-not-found >/dev/null 2>&1 || true
kc -n "$LAB_NAMESPACE" delete rolebinding spark-client-driver --ignore-not-found >/dev/null 2>&1 || true

kc -n "$LAB_NAMESPACE" rollout status deploy/silo --timeout=180s >/dev/null
# Silo bundles the `mcli` client; MC_HOST_<alias> avoids writing a config file.
kc -n "$LAB_NAMESPACE" exec deploy/silo -- sh -c \
  'MC_HOST_local="http://$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD@127.0.0.1:9000" mcli mb --ignore-existing "local/$0" >/dev/null' \
  "$SILO_BUCKET"

# Shared non-root Silo user restricted to bucket spark-data. Notebooks get these
# credentials; the root key never leaves Silo/startcluster (design §3.5).
kc -n "$LAB_NAMESPACE" exec deploy/silo -- sh -c '
  set -e
  export MC_HOST_local="http://$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD@127.0.0.1:9000"
  cat > /tmp/spark-data-rw.json <<JSON
{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Action":["s3:*"],"Resource":["arn:aws:s3:::'"$SILO_BUCKET"'","arn:aws:s3:::'"$SILO_BUCKET"'/*"]}]}
JSON
  mcli admin user add local "$0" "$1" >/dev/null 2>&1 || true
  mcli admin policy create local spark-data-rw /tmp/spark-data-rw.json >/dev/null 2>&1 || true
  mcli admin policy attach local spark-data-rw --user "$0" >/dev/null 2>&1 || true
' "$SILO_SHARED_ACCESS_KEY" "$SILO_SHARED_SECRET_KEY"

# Shared credentials Secret; the Hub hook copies it into each user namespace.
kc -n "$LAB_NAMESPACE" create secret generic silo-shared-credentials \
  --from-literal=accessKey="$SILO_SHARED_ACCESS_KEY" \
  --from-literal=secretKey="$SILO_SHARED_SECRET_KEY" \
  --dry-run=client -o yaml | kc apply -f - >/dev/null

log "5/8 Publishing portal page"
kc -n "$LAB_NAMESPACE" create configmap portal-html --from-file=index.html=portal/index.html \
  --dry-run=client -o yaml | kc apply -f - >/dev/null
kc apply -f k8s/40-portal.yaml >/dev/null
# Pick up a changed index.html (ConfigMap volume updates are delayed otherwise).
kc -n "$LAB_NAMESPACE" rollout restart deploy/portal >/dev/null

ensure_chart() { # repo-name repo-url chart version
  hm repo add "$1" "$2" >/dev/null 2>&1 || true
  if ! hm search repo "$3" --version "$4" 2>/dev/null | grep -q "$3"; then
    hm repo update "$1" >/dev/null
  fi
}

log "6/8 Installing Traefik ingress controller (port $LAB_PORT)"
ensure_chart traefik https://traefik.github.io/charts traefik/traefik "$TRAEFIK_CHART_VERSION"
hm upgrade --install traefik traefik/traefik \
  --namespace "$INGRESS_NAMESPACE" --create-namespace \
  --version "$TRAEFIK_CHART_VERSION" \
  --values traefik/values.yaml \
  --set ports.web.exposedPort="$LAB_PORT" \
  --wait --timeout 5m >/dev/null
# Ingress and Middleware objects need the Traefik CRDs installed above.
kc apply -f k8s/50-ingress.yaml >/dev/null

log "7/8 Installing JupyterHub"
ensure_chart jupyterhub https://hub.jupyter.org/helm-chart/ jupyterhub/jupyterhub "$JUPYTERHUB_CHART_VERSION"
hm upgrade --install jupyterhub jupyterhub/jupyterhub \
  --namespace "$LAB_NAMESPACE" \
  --version "$JUPYTERHUB_CHART_VERSION" \
  --values jupyterhub/values.yaml \
  --set-file hub.extraConfig.sparkLabMultiuser=jupyterhub/spark_lab_hook.py \
  --set-string singleuser.image.tag="$RUNTIME_TAG" \
  --set-string "singleuser.initContainers[0].image=$RUNTIME_IMAGE" \
  --set-string singleuser.extraEnv.SPARK_LAB_RUNTIME_IMAGE="$RUNTIME_IMAGE" \
  --wait --timeout 5m >/dev/null

log "8/8 Waiting for http://localhost:$LAB_PORT/hub/health"
for i in $(seq 1 60); do
  code=$(curl -s -o /dev/null -w '%{http_code}' "http://localhost:$LAB_PORT/hub/health" || true)
  [ "$code" = "200" ] && break
  [ "$i" -eq 60 ] && die "JupyterHub is not reachable through the Ingress (last HTTP code: $code)"
  sleep 2
done

# Pre-register the admin `spark` so nobody can claim that username first
# (NativeAuthenticator auto-authorizes a signup whose name is in admin_users).
# Signing up an existing user is a no-op, so this is safe to repeat.
base="http://localhost:$LAB_PORT"
jar=$(mktemp)
xsrf=$(curl -s -c "$jar" "$base/hub/signup" | sed -n 's/.*name="_xsrf" value="\([^"]*\)".*/\1/p' | head -1)
signup_code=$(curl -s -b "$jar" -o /dev/null -w '%{http_code}' \
  --data-urlencode "_xsrf=$xsrf" \
  --data-urlencode "username=$JUPYTER_USER" \
  --data-urlencode "signup_password=$JUPYTER_PASSWORD" \
  --data-urlencode "signup_password_confirmation=$JUPYTER_PASSWORD" \
  "$base/hub/signup")
log "    ensured admin '$JUPYTER_USER' is registered (HTTP $signup_code)"
rm -f "$jar"

cat <<EOF

Spark Platform Learning Lab is up.

  Portal (all links):  http://localhost:$LAB_PORT/
$(for ip in $(lan_ips); do echo "  From the LAN:        http://$ip:$LAB_PORT/"; done)

  Admin login:         user=$JUPYTER_USER  password=$JUPYTER_PASSWORD
  New users:           self-register at /hub/signup, then admin approves at /hub/authorize
  Silo Console login:  accessKey=$SILO_ACCESS_KEY  secretKey=$SILO_SECRET_KEY
  (stored in .lab/credentials.env)

Stop with ./stopcluster.sh (data on PVCs is kept).
EOF
